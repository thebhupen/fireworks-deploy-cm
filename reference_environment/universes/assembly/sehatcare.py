"""SehatCare state: providers, generated slot inventory, patients from the household, history and payments."""

from __future__ import annotations

from datetime import date, datetime, timedelta
from typing import Any

from reference_environment.universes.apps.common import parse_date

from .content import unique

WEEKDAYS = ("Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun")


def slot_id(owner_id: str, day: date, start: str, mode: str) -> str:
    return f"{owner_id}-{day.strftime('%Y%m%d')}-{start.replace(':', '')}-{mode}"


def _generated_slots(content: dict[str, Any]) -> dict[str, dict[str, Any]]:
    window = content["slot_window"]
    first, last = parse_date(window["start"]), parse_date(window["end"])
    taken = set(content.get("taken_slots", []))
    slots = {}
    day = first
    while day <= last:
        for template in content["slot_templates"]:
            if WEEKDAYS[day.weekday()] not in template["days"]:
                continue
            for start in template["times"]:
                end = (datetime.strptime(start, "%H:%M") + timedelta(minutes=template["minutes"])).strftime("%H:%M")
                key = slot_id(template["owner_id"], day, start, template["mode"])
                slots[key] = {
                    "slot_id": key,
                    "owner_id": template["owner_id"],
                    "date": day.isoformat(),
                    "start_time": start,
                    "end_time": end,
                    "mode": template["mode"],
                    "available": key not in taken,
                }
        day += timedelta(days=1)
    unknown = taken - set(slots)
    if unknown:
        raise ValueError(f"taken_slots not generated by any template: {sorted(unknown)}")
    return slots


def build_sehatcare(
    content: dict[str, Any], people: dict[str, dict[str, Any]], addresses: dict[str, dict[str, Any]], phone: str
) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    """Return (SehatCare state, PaySetu payments with local keys)."""
    providers = {
        p["provider_id"]: {"home_collection": False, **p}
        for p in unique(content["providers"], "provider_id", "provider").values()
    }
    doctors = {d["doctor_id"]: d for d in unique(content["doctors"], "doctor_id", "doctor").values()}
    tests = {t["test_id"]: {"includes": [], "description": "", **t} for t in content["lab_tests"]}
    slots = _generated_slots(content)
    for slot in content.get("past_slots", []):
        if slot["slot_id"] in slots:
            raise ValueError(f"Duplicate slot {slot['slot_id']}")
        slots[slot["slot_id"]] = slot
    patients = {}
    for patient in content["patients"]:
        person = people[patient["person_id"]]
        patients[patient["patient_id"]] = {
            "patient_id": patient["patient_id"],
            "name": person["full_name"],
            "age": person["age"],
            "gender": person["gender"],
            "relation": patient["relation"],
        }
    state_addresses = {}
    for entry in content["addresses"]:
        address = addresses[entry["address_key"]]
        state_addresses[entry["address_id"]] = {
            "address_id": entry["address_id"],
            **{key: address[key] for key in ("label", "line1", "area", "city", "pincode")},
            "phone": phone,
        }
    appointments, payments = {}, []
    for appointment in unique(content["appointments"], "appointment_id", "appointment").values():
        slot = slots[appointment["slot_id"]]
        if appointment["kind"] == "consultation":
            doctor = doctors[appointment["doctor_id"]]
            if slot["owner_id"] != doctor["doctor_id"] or slot["mode"] not in doctor["modes"]:
                raise ValueError(f"{appointment['appointment_id']}: slot does not belong to {doctor['name']}")
            amount = doctor["consult_fee"]
            merchant = providers[doctor["provider_id"]]["name"]
        else:
            labs = {tests[test_id]["provider_id"] for test_id in appointment["test_ids"]}
            if labs != {slot["owner_id"]}:
                raise ValueError(f"{appointment['appointment_id']}: tests and slot are not from one lab")
            amount = sum(tests[test_id]["price"] for test_id in appointment["test_ids"])
            merchant = providers[slot["owner_id"]]["name"]
        slot["available"] = False
        key = f"appointment:{appointment['appointment_id']}"
        payments.append(
            {
                "key": key,
                "timestamp": appointment["booked_at"],
                "direction": "debit",
                "amount": amount,
                "counterparty_name": merchant,
                "source_id": appointment["payment"],
                "category": "health",
                "reference_app": "SehatCare",
                "reference_id": appointment["appointment_id"],
            }
        )
        appointments[appointment["appointment_id"]] = {
            "appointment_id": appointment["appointment_id"],
            "kind": appointment["kind"],
            "patient_id": appointment["patient_id"],
            "slot_id": appointment["slot_id"],
            "mode": slot["mode"],
            "amount": amount,
            "txn_id": key,
            "booked_at": appointment["booked_at"],
            "status": appointment["status"],
            "doctor_id": appointment.get("doctor_id"),
            "test_ids": list(appointment.get("test_ids", [])),
            "address_id": appointment.get("address_id"),
            "reschedule_count": 0,
            "refunded_amount": 0,
        }
    records = {
        r["record_id"]: {"appointment_id": None, "file_path": None, "results": [], **r}
        for r in unique(content.get("medical_records", []), "record_id", "medical record").values()
    }
    state = {
        "id_counters": {
            "SC-APT": len(appointments),
            "SC-REC": len(records),
            "SC-PAT": len(patients),
        },
        "providers": providers,
        "doctors": doctors,
        "lab_tests": tests,
        "slots": slots,
        "patients": patients,
        "addresses": state_addresses,
        "appointments": appointments,
        "medical_records": records,
    }
    return state, payments
